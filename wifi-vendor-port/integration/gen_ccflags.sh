# 生成把 adapted/ 接入目标内核 kbuild 所需的 ccflags（-I 清单 + compat 头）。
#
# 背景：原厂 Makefile 里 -I 了 40+ 个 $(srctree)/drivers/misc/mediatek/... 平台
# 私有头路径，主线树没有这些目录。adapted/ 已把私有栈自带的所有头文件保真
# 导出，因此改为「扫描 adapted/ 下所有含 .h 的目录」自动生成 -I，等价覆盖
# 原厂的私有头依赖，且不依赖目标树路径。
#
# 用法:
#   ./gen_ccflags.sh <adapted目录> <compat目录> [输出文件]
# 输出默认打印到 stdout，可直接 eval 或写进 Makefile。
set -u
ADP="${1:-adapted}"
CMP="${2:-compat}"
OUT="${3:-}"
BASELINE="${4:-auto}"
if [ "$BASELINE" = "auto" ]; then
  [ -d baseline ] && BASELINE=baseline || BASELINE=""
fi

# 让 adapted/ 自包含：把整个 compat/ 复制进 connectivity/compat/。
# 除 mtk_wifi_compat.h 外还有 soc/mediatek/emi.h、asm/unaligned.h 等
# 4.14 老路径别名头，必须一并部署才能命中 <soc/mediatek/emi.h>。
COMPAT_DST="$ADP/misc/mediatek/connectivity/compat"
if [ -d "$CMP" ]; then
    mkdir -p "$COMPAT_DST"
    cp -a "$CMP/." "$COMPAT_DST/"
fi
COMPAT_REL="${COMPAT_DST#$ADP/}"

emit_inc() {
  # 生成 -I 清单：所有含 .h 的目录 + 直到根的祖先。
  # 只加最深目录会漏掉 <mt-plat/xxx.h>、<conn_infra/xxx.h> 这类带路径 include。
  python3.11 - "$1" "$2" <<'PY'
import os, sys
root = os.path.abspath(sys.argv[1]); prefix = sys.argv[2]
dirs = set()
for dp, _, fns in os.walk(root):
    if any(f.endswith('.h') for f in fns):
        dirs.add(os.path.abspath(dp))
allr = set(dirs); allr.add(root)
for d in list(dirs):
    p = os.path.dirname(d)
    while p.startswith(root):
        allr.add(p); p = os.path.dirname(p)
for d in sorted(allr):
    rel = os.path.relpath(d, root)
    if rel == '.':
        print('subdir-ccflags-y += -I%s' % prefix)
    else:
        print('subdir-ccflags-y += -I%s/%s' % (prefix, rel))
PY
}

{
  echo "# Auto-generated by gen_ccflags.sh — MT6893 vendor WiFi stack -> mainline"
  echo "# 目标树接线：把下列 ccflags 追加到 connectivity 顶层 Makefile 的 ccflags-y"
  echo "#   \$(shell \$(src)/../../../../../wifi-vendor-port/integration/gen_ccflags.sh ...) "
  echo
  echo "# 1) compat 头目录（已由本脚本整体复制进 adapted/，部署后自包含）"
  echo "subdir-ccflags-y += -I\$(src)/$COMPAT_REL"
  echo
  echo "# 2) 私有栈 -I（含祖先目录，命中 <mt-plat/...> / <conn_infra/...> 等带路径 include）"
  emit_inc "$ADP" '$(src)'
  echo
  echo "# 3) 平台基线层 -I（tools/build_baseline.py 从 ares-r-oss 保真导出）"
  echo "#    \$(BASELINE) 指向 baseline/ 在目标树中的部署位置"
  if [ -n "$BASELINE" ] && [ -d "$BASELINE" ]; then
    emit_inc "$BASELINE" '$(BASELINE)'
  else
    echo "# 未找到 baseline/，跳过（本包不自带平台基线层）"
  fi
  echo
  echo "# 4) 内核内部头根（原厂 Makefile 的 -I\$(srctree)/net，供 wireless/core.h）"
  echo "subdir-ccflags-y += -I\$(srctree)/net"
  echo
  echo "# 5) 关键编译宏（对齐原厂 Makefile 的 MT6893/gen4m 分支）"
  echo "subdir-ccflags-y += -DCONFIG_MACH_MT6893"
  echo "subdir-ccflags-y += -DCONNAC_VER=2_0 -DCFG_BUILD_CONNAC2=true"
  echo "subdir-ccflags-y += -DWLAN_CHIP_ID=6893 -DMTK_COMBO_CHIP=CONNAC2X2_SOC3_0"
  echo "subdir-ccflags-y += -DCONFIG_MTK_COMBO_WIFI_HIF=axi"
} > "${OUT:-/dev/stdout}"

[ -n "$OUT" ] && echo "已写出: $OUT ($(wc -l < "$OUT") 行)" >&2
